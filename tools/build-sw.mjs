// Regenerates sw.js with the full precache list and a new cache version.
// Run before every push:  node tools/build-sw.mjs
import { readdirSync, statSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const skip = /^(\.git|tools|node_modules|sw\.js|README\.md|\.nojekyll|\.gitignore)/;
const files = [];
(function walk(dir) {
  for (const name of readdirSync(join(root, dir)).sort()) {
    const rel = dir ? dir + '/' + name : name;
    if (skip.test(rel) || name.startsWith('.')) continue;
    if (statSync(join(root, rel)).isDirectory()) walk(rel); else files.push(rel);
  }
})('');
const prev = existsSync(join(root, 'sw.js')) ? +(readFileSync(join(root, 'sw.js'), 'utf8').match(/ataraxia-v(\d+)/) || [0, 0])[1] : 0;
const version = prev + 1;
const assets = ['./', ...files.filter(f => f !== 'index.html').map(f => './' + f)];

writeFileSync(join(root, 'sw.js'), `// Generated by tools/build-sw.mjs. Do not edit by hand.
const CACHE = 'ataraxia-v${version}';
const ASSETS = ${JSON.stringify(assets, null, 1)};

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE)
    .then(c => Promise.all(ASSETS.map(u => fetch(new Request(u, { cache: 'reload' })).then(r => {
      if (!r.ok) throw new Error('precache failed: ' + u);
      return c.put(u, r);
    }))))
    .then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('ataraxia-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Cache first, so the app opens instantly and works with no network at all.
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then(async c => {
    const hit = await c.match(req, { ignoreSearch: true }) || (req.mode === 'navigate' ? await c.match('./') : null);
    if (hit) return hit;
    try { return await fetch(req); } catch (err) { return (await c.match('./')) || Response.error(); }
  }));
});
`);
console.log('sw.js -> ataraxia-v' + version + ', ' + assets.length + ' assets');
